"""Render the verification report committed next to the catalogue.

Deterministic on purpose: no run timestamps, so `--check` can compare a rebuild byte for byte.
"""

from __future__ import annotations

import collections
from typing import Dict, List, Tuple

import curation
from indonesia import CORROBORATION_KM, OFFICE_SANITY_KM, POLYGON_TOLERANCE_KM, Finding, IndonesiaResult
from legacy import Comparison
from sources import SOURCES, FetchedSource


def _table(headers: List[str], rows: List[List[object]]) -> List[str]:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for row in rows:
        out.append("| " + " | ".join(str(c).replace("|", "/") for c in row) + " |")
    return out


def render(
    fetched: List[FetchedSource],
    indonesia: IndonesiaResult,
    countries: List[Dict[str, object]],
    excluded: List[Tuple[str, str]],
    legacy_entries: List[Dict[str, object]],
    comparisons: List[Comparison],
    findings: List[Finding],
    version: str,
) -> str:
    lines: List[str] = [
        "# Region catalogue verification report",
        "",
        "Generated by `scripts/regions/build_regions.py`. Do not edit by hand; rebuild instead.",
        "",
        f"Catalogue version `{version}`.",
        "",
        "## Contents",
        "",
    ]
    lines += _table(["Part", "Count"], [
        ["Provinces", indonesia.counts.get("provinces", 0)],
        ["Kabupaten", indonesia.counts.get("kabupaten", 0)],
        ["Kota", indonesia.counts.get("kota", 0)],
        ["Countries (one entry each, at the capital)", len(countries)],
        ["Hidden legacy entries", len(legacy_entries)],
        ["Legacy ids aliased to a kota", len([c for c in comparisons if c.old_id != c.new_id])],
    ])
    lines += [
        "",
        "## How each point was verified",
        "",
        "Names, codes and seats of Indonesian kabupaten and kota come from Kepmendagri No 300.2.2-2430 "
        "Tahun 2025. A name must match the Wikidata item that carries the same administrative code "
        "(P2588), or the geoBoundaries polygon when Wikidata has no label.",
        "",
        f"The point is the regent's or mayor's office when OpenStreetMap maps one inside the regency "
        f"polygon (sanity limit {OFFICE_SANITY_KM:g} km to any other source). Otherwise it is the point "
        f"the most independent source groups agree on within {CORROBORATION_KM:g} km, and at least two "
        "groups must agree. GeoNames, Wikidata, Kepmendagri and OpenStreetMap each count once; a Wikidata "
        "coordinate identical to the Kepmendagri one counts as the same group, because one copied the other. "
        f"Every point must lie inside its own geoBoundaries ADM2 polygon (tolerance {POLYGON_TOLERANCE_KM:g} km).",
        "",
        "Countries are placed at the GeoNames capital. It must agree within 25 km with Wikidata's current "
        "capital or Natural Earth's capital point, and lie inside the country's Natural Earth map unit "
        "(tolerance 5 km).",
        "",
        "## Sources",
        "",
    ]
    lines += _table(["Source", "URL", "sha256", "Bytes"], [
        [SOURCES.get(f.key, {}).get("title", f.key), SOURCES.get(f.key, {}).get("url", "Overpass API, see sources.py"),
         f"`{f.sha256[:16]}`", f.size] for f in fetched
    ])
    lines += ["", "Wikidata is queried live (CC0); the queries are in `indonesia.py`, `countries.py` and `legacy.py`.", ""]

    by_source = collections.Counter(r.source.split(":")[0].split(" ")[0] for r in indonesia.resolved)
    support = collections.Counter(len(r.support) for r in indonesia.resolved)
    lines += ["## Where the Indonesian points came from", ""]
    lines += _table(["Chosen point", "Regencies"], [[k, v] for k, v in sorted(by_source.items())])
    lines += [""]
    lines += _table(["Independent groups in agreement", "Regencies"], [[k, v] for k, v in sorted(support.items(), reverse=True)])

    lines += ["", "## Manual decisions", ""]
    decisions: List[List[object]] = []
    for code, (fixed, why) in curation.NAME_FIXES.items():
        decisions.append([code, "name", fixed, why])
    for code, (seat, why) in curation.SEAT_FIXES.items():
        decisions.append([code, "seat", seat, why])
    for code, (names, why) in curation.SEAT_ALIASES.items():
        decisions.append([code, "seat alias", ", ".join(names), why])
    for code, (lat, lng, why) in curation.COORDINATE_OVERRIDES.items():
        decisions.append([code, "coordinate", f"{lat}, {lng}", why])
    for code, (gb, why) in curation.GEOBOUNDARIES_NAME.items():
        decisions.append([code, "boundary name", gb, why])
    for iso, (capital, why) in curation.COUNTRY_CAPITAL_OVERRIDES.items():
        decisions.append([iso, "capital", capital, why])
    lines += _table(["Code", "Kind", "Value", "Evidence"], decisions)

    lines += ["", "## Countries left out", ""]
    lines += _table(["ISO", "Reason"], [[iso, why] for iso, why in excluded])

    lines += ["", "## Previous catalogue compared", "",
              "Every id the previous catalogue shipped still resolves. Distance is from the old point to the verified one.", ""]
    lines += _table(["Old id", "Old name", "Old province", "Now", "Province", "Moved km"], [
        [c.old_id, c.old_name, c.old_province, f"{c.new_name} (`{c.new_id}`)", c.new_province, f"{c.moved_km:.1f}"]
        for c in sorted(comparisons, key=lambda c: -c.moved_km)
    ])

    notes = [f for f in findings if f.level == "note"]
    lines += ["", f"## Notes ({len(notes)})", ""]
    lines += _table(["Code", "Name", "Check", "Detail"], [[f.code, f.name, f.check, f.detail] for f in notes])

    lines += ["", "## Every kabupaten and kota", ""]
    lines += _table(["Code", "Name", "Seat", "Point", "Chosen from", "Agreeing groups", "km from Kepmendagri point"], [
        [r.entry["admin_code"], r.entry["official_name"], r.entry["city"], f"{r.entry['latitude']}, {r.entry['longitude']}",
         r.source, ", ".join(r.support), f"{r.moved_km:.1f}"]
        for r in indonesia.resolved
    ])
    return "\n".join(lines) + "\n"
